const normalizeExerciseName = (value: string): string =>
  value.trim().toLocaleLowerCase("zh-CN").replace(/[\s·_—-]+/g, "");

const exerciseSearchIndex = new Map<string, ExerciseGuide>();
for (const item of EXERCISE_GUIDES) {
  for (const key of [item.id, item.name, ...item.aliases]) {
    exerciseSearchIndex.set(normalizeExerciseName(key), item);
  }
}

/** 支持按稳定 ID、中文动作名或别名查找教学。 */
export const findExerciseGuide = (nameOrId: string): ExerciseGuide | undefined =>
  exerciseSearchIndex.get(normalizeExerciseName(nameOrId));
